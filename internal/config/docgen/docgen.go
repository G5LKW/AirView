// Package docgen extracts the documentation comments of the configuration
// structs in internal/model, so that the commented example config
// (internal/config/airview.example.jsonc) and the reference document
// (docs/CONFIG.md) are generated from the same doc comments developers
// write next to the fields. It uses only the standard library's go/parser.
//
// The result maps "<Type>" to the type's doc comment and "<Type>.<Field>"
// to the field's doc comment followed by its trailing line comment, each
// collapsed to a single line.
package docgen

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// Extract parses the non-test Go files in dir and returns the struct and
// field documentation.
func Extract(dir string) (map[string]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	fset := token.NewFileSet()
	docs := map[string]string{}
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		for _, d := range f.Decls {
			gd, ok := d.(*ast.GenDecl)
			if !ok || gd.Tok != token.TYPE {
				continue
			}
			for _, sp := range gd.Specs {
				ts := sp.(*ast.TypeSpec)
				st, ok := ts.Type.(*ast.StructType)
				if !ok {
					continue
				}
				tdoc := ts.Doc
				if tdoc == nil && len(gd.Specs) == 1 {
					tdoc = gd.Doc
				}
				if s := clean(tdoc.Text()); s != "" {
					docs[ts.Name.Name] = s
				}
				for _, fld := range st.Fields.List {
					text := clean(fld.Doc.Text())
					if c := clean(fld.Comment.Text()); c != "" {
						if text != "" && !strings.HasSuffix(text, ".") {
							text += "."
						}
						text = strings.TrimSpace(text + " " + c)
					}
					if text == "" {
						continue
					}
					for _, n := range fld.Names {
						docs[ts.Name.Name+"."+n.Name] = text
					}
				}
			}
		}
	}
	return docs, nil
}

// clean collapses a comment to one line.
func clean(s string) string {
	s = strings.Join(strings.Fields(s), " ")
	s = strings.TrimSuffix(s, " //")
	if s == "//" {
		return ""
	}
	return s
}

// GoSource renders docs as the generated Go file of package pkg holding
// "var <varName> = map[string]string{...}".
func GoSource(pkg, varName string, docs map[string]string) ([]byte, error) {
	keys := make([]string, 0, len(docs))
	for k := range docs {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go run ./gen; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	fmt.Fprintf(&b, "// %s holds the doc comments of the configuration structs in\n// internal/model, keyed \"Type\" and \"Type.Field\" (see package docgen).\n", varName)
	fmt.Fprintf(&b, "var %s = map[string]string{\n", varName)
	for _, k := range keys {
		fmt.Fprintf(&b, "\t%s: %s,\n", strconv.Quote(k), strconv.Quote(docs[k]))
	}
	b.WriteString("}\n")
	return format.Source(b.Bytes())
}
