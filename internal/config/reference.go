// ReferenceMarkdown returns docs/CONFIG.md: the configuration reference
// generated from model.Config, its doc comments and the defaults.
func ReferenceMarkdown() string { return RenderReference(modelDocs) }

// RenderReference renders the configuration reference with the given model
// documentation (the generator passes freshly extracted docs).
func RenderReference(docs map[string]string) string {
	var b strings.Builder
	p := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	p("<!-- Code generated by go generate ./internal/config; DO NOT EDIT. -->\n\n")
	p("# AirView configuration reference\n\n")
	p("Every AirView setting can be set without the web UI: in a configuration file, through an environment variable or on the command line. This document lists all of them. It is generated from the source code (`internal/model`), so it always matches the build it ships with; `airview config example` prints the same information as a commented configuration file.\n\n")
	p("## Where settings come from\n\n")
	p("The effective configuration is assembled from these layers; a later layer overrides an earlier one, setting by setting:\n\n")
	p("1. **Defaults** built into AirView (the values in the tables below).\n")
	p("2. **`config.json`** in the data directory. AirView writes this file itself: the settings page of the web UI saves here. It is plain JSON (comments are tolerated but removed on the next save).\n")
	p("3. **The operator file**, JSON with comments, which AirView only reads. It is taken from `-config <file>`, else `$AIRVIEW_CONFIG`, else `airview.jsonc` in the data directory when that file exists. List only the settings you want to pin; everything else keeps its `config.json` value. Typical location on a Linux server: `/etc/airview/airview.jsonc`.\n")
	p("4. **Environment variables** `AIRVIEW_*` (one per setting, listed below).\n")
	p("5. **Command-line overrides** `-set path=value` (repeatable), e.g. `-set http.port=8080`. The older `-port` and `-demo` flags keep working.\n\n")
	p("Settings from layers 3-5 are *locked*: they are in force and visible in the UI, but saving in the UI never writes them to `config.json`. Remove the override and the `config.json` value applies again. Secrets given this way therefore never end up on disk.\n\n")
	p("The data directory is `-data <dir>` or `$AIRVIEW_DATA`; without either it is `data` next to the executable when writable, else the per-user configuration directory (`%%AppData%%\\AirView`, `~/.config/AirView`).\n\n")
	p("## File format\n\n")
	p("The operator file is JSON plus `//` line comments, `/* */` block comments and trailing commas. Names are case-sensitive. Unknown names, wrong value types and duplicate names are errors that `airview config check` reports with file, line and column. Values outside their allowed range are corrected when AirView starts (the correction is logged) and are reported by `airview config check`.\n\n")
	p("Lists (`antennas`, `feeds`, `uplinks`, `ui.rangeRingsKm`, ...) are replaced as a whole: a list in the operator file replaces the list from `config.json`.\n\n")
	p("Factory defaults of the lists: one omnidirectional antenna (`vertical`, channel 0) and one feed `beast` reading Beast binary from `localhost:30005`, the standard Beast output of readsb / dump1090. For a Radarcape, point a Beast feed at its host name or address, port 10003. An existing `config.json` keeps its own antennas and feeds on upgrade; a factory reset restores these defaults.\n\n")
	p("## Environment variables\n\n")
	p("The variable name is `AIRVIEW_` followed by the setting path in upper-case snake case, with `_` between the levels: `http.port` is `AIRVIEW_HTTP_PORT`, `aggregator.limits.maxStations` is `AIRVIEW_AGGREGATOR_LIMITS_MAX_STATIONS`.\n\n")
	p("- Booleans: `true`/`false` (also `1`/`0`, `yes`/`no`, `on`/`off`).\n")
	p("- Lists of numbers or strings: comma separated (`AIRVIEW_UI_RANGE_RINGS_KM=50,100,200`) or JSON (`[50,100,200]`); an empty value is an empty list.\n")
	p("- Lists of objects: the whole list as JSON (`AIRVIEW_UPLINKS='[{\"id\":\"club\",\"host\":\"agg.example.org\"}]'`), one element as JSON (`AIRVIEW_UPLINKS_0='{...}'`) or one field of one element (`AIRVIEW_UPLINKS_0_ENROL_TOKEN=...`). Elements are numbered from 0; using the next free number adds an element.\n")
	p("- Any variable can be suffixed `_FILE` to read the value from a file (for Docker/systemd secrets), e.g. `AIRVIEW_HUB_PASSWORD_FILE=/run/secrets/hub`. One trailing newline is removed.\n")
	p("- `AIRVIEW_CONFIG` (operator file) and `AIRVIEW_DATA` (data directory) are not settings themselves. Unknown `AIRVIEW_*` variables are ignored with a warning.\n\n")
	p("## Commands\n\n")
	p("| Command | What it does |\n|---|---|\n")
	p("| `airview config check [-data dir] [-config file] [-set p=v]...` | Loads every layer without changing anything and reports syntax errors, unknown settings, wrong types and out-of-range values with their location. Exit status 0 = valid (warnings allowed), 1 = errors, 2 = usage error. `-json` prints the report as JSON, `-q` prints errors only. |\n")
	p("| `airview config print [-data dir] [-config file] [-sources] [-json]` | Prints the effective configuration with secrets redacted. `-sources` adds a comment with the origin of every overridden setting. |\n")
	p("| `airview config example [-o file]` | Writes the fully commented example file (every setting at its default). |\n")
	p("| `airview config env` | Lists every environment variable with its setting and default. |\n\n")
	p("## Secrets\n\n")
	p("`http.adminPasswordHash`, `hub.password`, `remote.password`, `uplinks[].enrolToken`, `aggregator.outputToken` and `aggregator.tlsKey` are secrets: the API and `airview config print` show only `\"set\"` or `\"\"`. Prefer environment variables (`_FILE` variants) or an operator file readable only by the service account (`chmod 600`). `http.adminPasswordHash` may be given as `plain:<password>` in the operator file or environment; it is hashed when loaded.\n\n")
	writeStorageProfiles(p)
	p("## Settings\n\n")

	def, _ := Validate(model.DefaultConfig())
	defs := map[string]any{}
	collectDefaults(reflect.ValueOf(def), "", defs)
	collectDefaults(reflect.ValueOf(model.DefaultUplink()), "uplinks[]", defs)

	// Group fields by top-level section, then by sub-section.
	type group struct {
		section string
		fields  []FieldInfo
	}
	var groups []*group
	byName := map[string]*group{}
	for _, f := range Fields() {
		sec := f.Section
		if f.Kind == KindStructList {
			sec = f.Path + "[]" // the list itself is documented in its element table's intro
		}
		g := byName[sec]
		if g == nil {
			g = &group{section: sec}
			byName[sec] = g
			groups = append(groups, g)
		}
		if f.Kind != KindStructList {
			g.fields = append(g.fields, f)
		}
	}
	for _, g := range groups {
		top, _, _ := strings.Cut(strings.TrimSuffix(g.section, "[]"), ".")
		top, _, _ = strings.Cut(top, "[")
		heading := "###"
		title := sectionTitles[top]
		if g.section == top || g.section == top+"[]" {
			heading = "###"
		} else {
			heading = "####"
			title = "`" + g.section + "`"
		}
		if title == "" {
			title = "`" + g.section + "`"
		}
		if g.section != "" && (g.section == top || g.section == top+"[]") {
			title += " (`" + g.section + "`)"
		}
		p("%s %s\n\n", heading, title)
		if strings.HasSuffix(g.section, "[]") {
			list := strings.TrimSuffix(g.section, "[]")
			lf, _ := FieldByPath(list)
			if d := fieldDoc(docs, list); d != "" {
				p("%s\n\n", d)
			}
			if d := typeDoc(docs, lf.Type.Elem()); d != "" {
				p("%s\n\n", d)
			}
			p("Environment: `%s` (whole list as JSON), `%s_<n>` (one element as JSON), `%s_<n>_<FIELD>` (one field). Each element has these fields:\n\n", lf.Env, lf.Env, lf.Env)
		} else if g.section != "" {
			if t, ok := sectionType(g.section); ok && typeDoc(docs, t) != "" {
				p("%s\n\n", typeDoc(docs, t))
			}
		}
		p("| Setting | Type | Default | Environment variable | Description |\n|---|---|---|---|---|\n")
		for _, f := range g.fields {
			dv := "–"
			if v, ok := defs[f.Path]; ok {
				dv = "`" + mdEscape(fmtDefault(v)) + "`"
			}
			if f.Secret {
				dv += " (secret)"
			}
			p("| `%s` | %s | %s | `%s` | %s |\n", f.Path, f.Kind, dv, f.Env, mdEscape(fieldDoc(docs, f.Path)))
		}
		p("\n")
	}
	return b.String()
}

func sectionType(section string) (reflect.Type, bool) {
	segs, ok := parsePath(strings.ReplaceAll(section, "[]", "[0]"))
	if !ok {
		return nil, false
	}
	t, ok := typeAt(segs)
	return t, ok && t.Kind() == reflect.Struct
}

// collectDefaults records the value of every non-struct field of v by path.
func collectDefaults(v reflect.Value, prefix string, out map[string]any) {
	t := v.Type()
	for i := 0; i < t.NumField(); i++ {
		name, ok := jsonName(t.Field(i))
		if !ok {
			continue
		}
		path := name
		if prefix != "" {
			path = prefix + "." + name
		}
		fv := v.Field(i)
		if fv.Kind() == reflect.Struct {
			collectDefaults(fv, path, out)
			continue
		}
		out[path] = fv.Interface()
	}
}

func fmtDefault(v any) string {
	rv := reflect.ValueOf(v)
	if rv.Kind() == reflect.Slice {
		if rv.Len() == 0 {
			return "[]"
		}
		if rv.Type().Elem().Kind() == reflect.Struct {
			return fmt.Sprintf("%d entries", rv.Len())
		}
	}
	return scalarJSON(reflect.ValueOf(v))
}

func mdEscape(s string) string {
	return strings.NewReplacer("|", `\|`, "\n", " ").Replace(s)
}

// writeStorageProfiles writes the "Storage profiles" chapter: what each
// value of storage.profile does and what a power cut can lose
// (docs/perf/DB-EFFICIENCY-DESIGN.md §4.1, §4.3).
func writeStorageProfiles(p func(format string, a ...any)) {
	p("## Storage profiles\n\n")
	p("`storage.profile` decides how often the database writes to disk and how much memory its caches use. It never changes what is stored, kept or shown. `auto` (the default, also written `\"\"`) picks:\n\n")
	p("- `server` in aggregator mode (for `airview.db` and `stations.db`);\n")
	p("- `low-wear` when the data directory is on an SD / MMC card (Linux: block device major 179 in `/proc/self/mountinfo`) or the host is a Linux ARM board with at most 1 GiB of RAM;\n")
	p("- `standard` everywhere else (Windows, x86 Linux, a Raspberry Pi with the data on an SSD).\n\n")
	p("The profile in force, and why `auto` chose it, is written to the log at start, shown by `airview db profile` and in `GET /api/db/stats` (`profile`). Single values can be changed with `storage.tuning.*` (0 = the profile's value).\n\n")
	p("| Value | `standard` | `low-wear` | `server` |\n|---|---|---|---|\n")
	p("| Group commit of queued rows (`tuning.flushSec`) | 10 s | 30 s | 5 s |\n")
	p("| Trail points written | every 60 s | every 60 s | aggregator lanes |\n")
	p("| Coverage / signal / elevation statistics of the day (`tuning.incFlushSec`) | every 60 s | every 300 s | aggregator lanes |\n")
	p("| Heat-map increments (`tuning.heatFlushSec`) | every 300 s | every 900 s | aggregator lanes |\n")
	p("| Partial `range_hour` row of the open hour | every 15 min | every 30 min | aggregator lanes |\n")
	p("| All-time aircraft rows of the aircraft in view (`tuning.aircraftFlushSec`; a new aircraft within 15 s, readers get rows at most 60 s old) | every 300 s | every 900 s | every 300 s |\n")
	p("| Trail tail sealed into compressed chunks | every 5 min | every 10 min | every 5 min |\n")
	p("| WAL checkpoint (`tuning.walSoftMB`, `tuning.checkpointSec`) | 40 MiB or 5 min | 48 MiB or 10 min | 64 MiB or 60 s |\n")
	p("| WAL hard cap / size limit after a reset | 64 MiB / 64 MiB | 64 MiB / 64 MiB | 512 MiB / 128 MiB |\n")
	p("| Writer page cache (`tuning.cacheMB`) | 16 MiB | 8 MiB (4 MiB on 32-bit) | 64 MiB |\n")
	p("| Reader connections x cache (`tuning.readConns`) | 4 x 8 MiB | 2 x 4 MiB (3 with >= 2 GiB RAM) | 8 x 16 MiB |\n")
	p("| Idle reader connections closed after | 10 min | 2 min | never |\n")
	p("| Memory-mapped I/O (`tuning.mmapMB`; Linux / macOS) | 256 MiB | 64 MiB | 1 GiB |\n")
	p("| Map tile cache cap (`AIRVIEW_TILECACHE_MB` overrides it) | 512 MB | 128 MB | 512 MB |\n\n")
	p("Memory-mapped I/O is never used on 32-bit systems, and on Windows only when `tuning.mmapMB` asks for it (Windows cannot shrink a file while a connection maps it, so the space freed by retention would never be returned). Checkpoints run on their own connection between two commits, never inside one; in practice the time limit triggers them (a few per hour), the size only after a burst such as the migration. `synchronous=NORMAL` with the write-ahead log is used by every profile: a crash, a killed process, a power cut or a full disk never damages the database file.\n\n")
	p("Statistics held in memory between two writes are always part of what the web pages and the API show, so a page looks the same with every profile.\n\n")
	p("### What a power cut can lose\n\n")
	p("A clean stop (service stop, `SIGTERM`, Ctrl+C, closing the window, a Windows or Linux shutdown) writes everything first; the Pi unit allows 120 s for that. An application crash or a killed process loses what was held in memory. A power cut additionally loses commits the operating system had not written to the card yet (Linux writes dirty pages back within about 30 s, Windows within seconds):\n\n")
	p("| Data | `standard` | `low-wear` | 1.0 |\n|---|---|---|---|\n")
	p("| Trail points | <= 70 s + write-back | <= 90 s + write-back | 15 s |\n")
	p("| Coverage, signal and elevation statistics | <= 60 s + write-back | <= 5 min + write-back | 15 s |\n")
	p("| Heat-map increments | <= 5 min + write-back | <= 15 min + write-back | 15 s |\n")
	p("| Range statistics of the open hour (maximum, percentiles) | <= 15 min + write-back | <= 30 min + write-back | 5 min |\n")
	p("| Small rows (Locate Me samples, met observations, events, latency, NTP) | <= 10 s + write-back | <= 30 s + write-back | 2 s |\n")
	p("| Flight rows | <= 60 s + write-back | <= 60 s + write-back | 60 s |\n")
	p("| Aircraft rows (messages, positions, last seen of the aircraft in view) | <= 5 min + write-back | <= 15 min + write-back | 60 s |\n\n")
	p("The `server` profile commits every 5 s; the aggregator's per-station statistics follow `aggregator.lanes.*` as before.\n\n")
	p("### Storage layout migration\n\n")
	p("A database written by AirView 1.0 is converted to the 1.1 layout in the background after the first start (trails into compressed chunks, compact heat, range and met tables). The station works normally meanwhile; every step is a separate transaction, so a crash or power cut resumes where it stopped. Before the first step AirView writes a backup `<data>/backup/airview-pre-1.1-<date>.db` when the disk has room for it (`storage.backupBeforeMigrate`: `auto`; `always` = no migration without a backup; `never`). The automatic backup is deleted 14 days after the migration finished. `airview db migrate --status` shows the progress, `--backup` writes a backup now, `--now` finishes the migration at once while AirView is stopped. The space the old layout used is returned to the disk over the following hours; a file that was created without incremental auto-vacuum keeps it for new rows instead (the log says so) until `airview db vacuum` runs with AirView stopped. Going back to 1.0 is only possible by restoring that backup.\n\n")
}
