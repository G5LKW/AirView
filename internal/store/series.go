package store

import (
	"context"
	"database/sql"
	"strconv"
)

// Per-station reads on stations.db.
//
// The statistics tables are keyed time first ((t, ant) or (day, ant, ...)),
// which keeps writes, rollups and retention cheap. A query for one station
// over a time range, "ant = ? AND t BETWEEN ? AND ?", would scan the rows of
// every station in that range: with 1,000 stations, a day of stats_minute is
// ~3 million rows. SeriesIn rewrites the range as "t IN (every step of the
// range)", which SQLite answers with one primary-key probe (t = ?, ant = ?)
// per step - 1,440 probes for a day of minutes, whatever the number of
// stations. The step values are generated by a recursive CTE, so no bound
// parameters are spent on them.

// seriesMaxSteps bounds the steps of one SeriesIn; longer ranges fall back
// to a plain range condition.
const seriesMaxSteps = 200_000

// SeriesIn returns a WITH clause and a condition that select the rows whose
// column col is one of the aligned values from, from+step, ... <= to: with
// is "WITH RECURSIVE ..." (to be placed before SELECT), cond is
// "<col> IN (SELECT v FROM <cte>)", args are the arguments of with (they
// precede all others). from is rounded up to a multiple of step. When the
// range is empty, cond is "0" (no rows); when it is longer than
// seriesMaxSteps steps, with is "" and cond a plain range condition. col
// must be a trusted identifier; name is the CTE name (distinct per query).
func SeriesIn(name, col string, step, from, to int64) (with, cond string, args []any) {
	if step <= 0 {
		step = 1
	}
	from = floorDiv(from+step-1, step) * step
	if from > to {
		return "", "0", nil
	}
	if (to-from)/step > seriesMaxSteps {
		return "", col + " >= " + strconv.FormatInt(from, 10) + " AND " + col + " <= " + strconv.FormatInt(to, 10), nil
	}
	st := strconv.FormatInt(step, 10)
	with = "WITH RECURSIVE " + name + "(v) AS (SELECT ? UNION ALL SELECT v + " + st + " FROM " + name +
		" WHERE v + " + st + " <= ?) "
	return with, col + " IN (SELECT v FROM " + name + ")", []any{from, to}
}

// stepOf is the alignment of the time column of the per-antenna tables.
func stepOf(table string) int64 {
	switch table {
	case "stats_minute":
		return 60
	case "stats_day":
		return 86400
	case "coverage", "signal_hist", "elev_hist":
		return 1
	}
	return 3600 // stats_hour, range_hour
}

// timeCond returns the WITH prefix, the time condition and its arguments
// for a per-antenna read of table over [from, to] (to <= 0 or huge: open).
// On airview.db it is the plain range; on stations.db the range is clamped
// to the rows present and turned into a SeriesIn.
func (s *Store) timeCond(ctx context.Context, q querier, table, col string, from, to int64) (with, cond string, args []any, err error) {
	if s.kind != KindStations {
		return "", col + " >= ? AND " + col + " <= ?", []any{from, to}, nil
	}
	var lo, hi sql.NullInt64
	// Two queries: SQLite answers a lone MIN() or MAX() of the key's first
	// column with one b-tree probe, but MIN() and MAX() together with a scan.
	if err := q.QueryRowContext(ctx, `SELECT (SELECT MIN(`+col+`) FROM `+table+`), (SELECT MAX(`+col+`) FROM `+table+`)`).Scan(&lo, &hi); err != nil {
		return "", "", nil, err
	}
	if !lo.Valid {
		return "", "0", nil, nil
	}
	from, to = max(from, lo.Int64), min(to, hi.Int64)
	with, cond, args = SeriesIn("ts_"+col, col, stepOf(table), from, to)
	return with, cond, args, nil
}

// orderByT is the ORDER BY clause of the per-antenna readers: on stations.db
// none (an ORDER BY t would make SQLite walk the time key instead of
// probing it per step; the readers sort in Go).
func (s *Store) orderByT() string {
	if s.kind == KindStations {
		return ""
	}
	return " ORDER BY t"
}
